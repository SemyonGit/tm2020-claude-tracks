"""Build docs/jump_table.md + CSV from jumps.csv (issue #10).

Usage: python jump_table.py <jumps.csv> <out.md> [top=30]
"""
import csv, sys
from collections import defaultdict
import numpy as np

SKIP = {"?", "OutsideMap"}
CELL, LAYER = 32.0, 8.0


def q(a, p):
    return float(np.percentile(a, p))


def main(src, out, top=30):
    rows = [r for r in csv.DictReader(open(src)) if r["takeoff"] not in SKIP]
    by = defaultdict(list)
    for r in rows:
        by[r["takeoff"]].append(r)
    stats = []
    for name, js in by.items():
        f = lambda k: np.array([float(j[k]) for j in js])
        sp, ang, dist, dy, air = f("speed_kmh"), f("angle_deg"), f("dist_m") / CELL, f("dy_m") / LAYER, f("air_s")
        landings = defaultdict(int)
        for j in js:
            landings[j["landing"]] += 1
        stats.append({
            "takeoff": name, "jumps": len(js), "maps": len({j["map_uid"] for j in js}),
            "speed_p25": q(sp, 25), "speed_med": q(sp, 50), "speed_p75": q(sp, 75),
            "angle_med": q(ang, 50), "dist_med": q(dist, 50), "dist_p90": q(dist, 90),
            "dy_med": q(dy, 50), "air_med": q(air, 50),
            "top_landing": max(landings, key=landings.get),
        })
    # rank by how many different maps use the block: avoids one map's spam dominating
    stats.sort(key=lambda s: (-s["maps"], -s["jumps"]))
    with open(out.replace(".md", ".csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(stats[0]))
        w.writeheader()
        w.writerows({k: (round(v, 2) if isinstance(v, float) else v) for k, v in s.items()} for s in stats)
    total = len(list(csv.DictReader(open(src))))
    with open(out, "w") as fh:
        fh.write(f"""# Kacky jump table

Measured from **{total:,} jumps** in the top-5 ghosts of the official Kacky maps
(KR1–6, KX1–4; kacky.gg + trackmania.io), generated by `tools/physics/jump_table.py`.
A jump = ≥0.2 s airborne. Takeoff block = block under the last ground sample.

- Ranked by **number of maps** using the block as a takeoff (not raw count).
- Distance in blocks (32 m), height change in layers (8 m, negative = landing lower).
- Speeds are what the **world-record holders** hit, i.e. the upper end of what's possible.
- Excluded: unknown takeoff and `OutsideMap` (stadium scenery beyond the grid, can't be placed).
- `StadiumGround` = the baked grass floor.
- Full data: `jump_table.csv`. Predict new jumps with `tools/physics/jump.py`.

| # | Takeoff block | Maps | Jumps | Speed km/h (p25–med–p75) | Angle° | Dist blocks (med / p90) | Δ height | Air s | Most common landing |
|---|---|---|---|---|---|---|---|---|---|
""")
        for i, s in enumerate(stats[:top], 1):
            fh.write(f"| {i} | `{s['takeoff']}` | {s['maps']} | {s['jumps']} | "
                     f"{s['speed_p25']:.0f}–**{s['speed_med']:.0f}**–{s['speed_p75']:.0f} | {s['angle_med']:.0f} | "
                     f"{s['dist_med']:.1f} / {s['dist_p90']:.1f} | {s['dy_med']:+.1f} | {s['air_med']:.2f} | "
                     f"`{s['top_landing']}` |\n")
    print(f"{len(stats)} takeoff blocks → {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 30)
